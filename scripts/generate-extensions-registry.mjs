// Scans the configured Studio extensions directory and writes a static-
// import registry file that Vite/Rollup can bundle. This is the frontend
// analogue of Soul core's own `_extensions` convention (see
// soul/src/extensions.js) -- but the mechanics differ: core's
// `fs.readdirSync` + `require()` runs in a long-lived Node process with a
// real filesystem, while this app ends up as a browser bundle with no
// filesystem at runtime, so every plugin module specifier has to be known
// statically at build time instead. Run via the `predev`/`prebuild` npm
// hooks, so it always runs before Vite starts.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';

dotenv.config();

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const outputPath = join(rootDir, 'src/lib/extensions/registry.generated.ts');

const extensionsDir = join(
  rootDir,
  process.env.STUDIO_EXTENSIONS_DIR || '_studio_extensions',
);

const writeRegistry = (pluginFiles) => {
  mkdirSync(dirname(outputPath), { recursive: true });

  const importLines = pluginFiles.map(
    (file, index) =>
      `import plugin_${index} from '${relative(
        dirname(outputPath),
        join(extensionsDir, file),
      )
        .replace(/\\/g, '/')
        .replace(/^(?!\.)/, './')}';`,
  );
  const exportLine =
    pluginFiles.length > 0
      ? `export const plugins: StudioPlugin[] = [${pluginFiles.map((_, i) => `plugin_${i}`).join(', ')}];`
      : 'export const plugins: StudioPlugin[] = [];';

  const contents = [
    '// AUTO-GENERATED by scripts/generate-extensions-registry.mjs -- do not edit.',
    "import type { StudioPlugin } from './types';",
    ...importLines,
    '',
    exportLine,
    '',
  ].join('\n');

  writeFileSync(outputPath, contents);
};

if (!existsSync(extensionsDir)) {
  console.log(
    `[soul-studio extensions] No extensions directory found at ${extensionsDir}, skipping`,
  );
  writeRegistry([]);
  process.exit(0);
}

const pluginFiles = readdirSync(extensionsDir).filter(
  (file) => file.endsWith('.ts') || file.endsWith('.js'),
);

if (pluginFiles.length === 0) {
  console.log(
    `[soul-studio extensions] No plugin files found in ${extensionsDir}`,
  );
} else {
  console.log(
    `[soul-studio extensions] Loading ${pluginFiles.length} plugin(s) from ${extensionsDir}`,
  );
}

writeRegistry(pluginFiles);
